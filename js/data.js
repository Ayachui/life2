function formatGameVersion(v = LIFE_DATA.gameVersion) {
  const labels = { alpha: "Альфа", beta: "Бета" };
  const num = `${v.major}.${v.minor}.${v.patch}`;
  const label = labels[v.stage];
  return label ? `${label} ${num}` : num;
}
